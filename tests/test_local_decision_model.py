"""Tests for the locally hosted decision model and local text model in jev_ultrafast."""

import os
import pytest
from jev_ultrafast import model
from jev_ultrafast.browser import fingerprint


def sample_page():
    state = {
        "url": "http://127.0.0.1:8000/planner",
        "title": "PG&E AI Assisted Public Planning Tool",
        "text": "PG&E Electric Distribution and DRP Planning Tool. Search substations, feeders, and hosting capacity.",
        "scroll": {"y": 0},
        "actions": [
            {"id": "e1", "kind": "fill", "label": "Ask about circuits, substations, hosting capacity...", "role": "textbox", "value": "", "node": 10},
            {"id": "e2", "kind": "click", "label": "Send", "role": "button", "value": "", "node": 20},
            {"id": "e3", "kind": "click", "label": "Explore Workflows", "role": "button", "value": "", "node": 30},
            {"id": "wait", "kind": "wait", "label": "Wait"},
        ],
    }
    state["fingerprint"] = fingerprint(state)
    return state


def test_make_valid_answer_properties():
    """Verify that synthetic answers generated by make_valid_answer always satisfy validate_choice."""
    ids = ["CLICK", "TYPE_TEXT", "SELECT", "DONE", "WAIT", "BLOCKED"]
    for selected in ids:
        ans = model.make_valid_answer(ids, selected)
        validated = model.validate_choice(ans, set(ids))
        assert validated["choice"] == selected
        assert abs(sum(validated["probabilities"].values()) - 1.0) < 0.02
        assert validated["probabilities"][selected] >= max(validated["probabilities"].values()) - 1e-6


def test_local_decision_model_live_ollama(monkeypatch):
    """Verify live inference of choose() using the locally hosted decision model via Ollama."""
    monkeypatch.setenv("USE_LOCAL_DECISION_MODEL", "true")
    monkeypatch.delenv("TYPESAFE_API_KEY", raising=False)

    page = sample_page()
    goal = "Search for Mission substation"

    decision = model.choose(page, goal, [])
    assert decision["operation"] in {"TYPE_TEXT", "CLICK", "DONE", "WAIT"}
    assert "choice" in decision
    assert decision["confidence"] > 0
    assert len(decision["probabilities"]) > 0
    assert "local" in decision["model"]


def test_local_text_model_live_ollama(monkeypatch):
    """Verify live field text generation using local Ollama model without external credentials."""
    monkeypatch.setenv("USE_LOCAL_TEXT_MODEL", "true")
    monkeypatch.delenv("TEXT_MODEL_API_KEY", raising=False)

    context = {
        "goal": "Search for PG&E Mission substation",
        "field": {"label": "Ask about circuits, substations...", "role": "textbox", "value": ""},
        "page": {"title": "PG&E Public Planner", "text": "PG&E Electric Distribution Planner"},
        "recent_actions": [],
    }

    text, helper = model.field_text(context)
    assert isinstance(text, str)
    assert len(text) > 0
    assert "mission" in text.lower() or "substation" in text.lower() or len(text) >= 3
